  /// All available image asset paths (for random fallback selection).
  static List<String> get allAvailablePaths => _imageMap.values.toList();

  /// Get the asset path for a word's image, or null if no image available.
  static String? getImagePath(String wordId) => _imageMap[wordId];

  /// Whether an image exists for this word.
  static bool hasImage(String wordId) => _imageMap.containsKey(wordId);

  /// Get the asset path for a WordEntry, or null.
  static String? getImageForEntry(WordEntry entry) => _imageMap[entry.id];

  /// Build an Image widget for a word, with a fallback icon.
  static Widget buildWordImage(
    String wordId, {
    double? width,
    double? height,
    BoxFit fit = BoxFit.cover,
    BorderRadius? borderRadius,
  }) {
    final path = getImagePath(wordId);

    Widget image;
    if (path != null) {
      image = Image.asset(
        path,
        width: width,
        height: height,
        fit: fit,
        errorBuilder: (_, __, ___) => _buildPlaceholder(width, height),
      );
    } else {
      image = _buildPlaceholder(width, height);
    }

    if (borderRadius != null) {
      return ClipRRect(borderRadius: borderRadius, child: image);
    }
    return image;
  }

  static Widget _buildPlaceholder(double? width, double? height) {
    return Container(
      width: width,
      height: height,
      color: const Color(0xFFEAE2CB),
      child: Center(
        child: Icon(
          Icons.image_rounded,
          size: (width ?? 64) * 0.4,
          color: const Color(0xFF5F5B4D),
        ),
      ),
    );
  }
